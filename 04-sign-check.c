#include <stdio.h>

int main(void)
{
    signed char d;

    printf("整数=");
    scanf("%hhd", &d);   /* %hhd は1バイトの整数（signed char）を読む書式 */

    if ((d & 0b00000000) == 0) {  /* TODO: 最上位ビットのマスクに変更 */
        printf("正の数です\n");
    } else {
        printf("負の数です\n");
    }
    return 0;
}
