// ==================================================
// 【種類】確認（そのまま実行する）
// 【内容】ビット演算子 | で、2つの数の論理和を1桁ずつ求める
// 【まずやること】
//   ・そのまま実行して「7」（2進数で 0000 0111）と表示されることを確認する
// 【やってみよう】
//   ① b を 0b00001100 に変える。紙に縦に並べて結果を予想してから実行する
//   ② | を ^ に変えると、結果はどうなる？ 予想してから実行する
// ==================================================
#include <stdio.h>

int main(void)
{
    int a = 0b00000011;   /* 10進数で3 */
    int b = 0b00000110;   /* 10進数で6 */
    int c = a | b;

    printf("%d\n", c);    /* 確認：7 */

    b = 0b00001100;
    c = a | b;
    printf("%d\n", c);    /* ① 15 */

    c = a ^ b;
    printf("%d\n", c);    /* ② 15（bを12に変更した場合） */

    b = 0b00000110;
    c = a ^ b;
    printf("%d\n", c);    /* 元のb=6に対するXOR：5 */
    return 0;
}
